'use strict';
/* RENDER-LEDGER — turn FINDINGS.json into results/99-ledger.md, deterministically.
 *
 * The complete record, rendered for reading. Nothing here is authored: every line
 * comes from the manifest, so the ledger cannot disagree with it.
 *
 * `test/test-results.js` runs this generator and asserts the committed file is
 * BYTE-IDENTICAL to fresh output. That is one check rather than a second parser
 * comparing field by field — and it means any edit to `FINDINGS.json` forces a
 * visible regeneration instead of quietly leaving the prose behind.
 *
 *     node tools/render-ledger.js          # print
 *     node tools/render-ledger.js --write  # write results/99-ledger.md
 *
 * Deterministic on purpose: no dates, no ordering that depends on anything but the
 * manifest's own order, no host-dependent formatting.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const M = JSON.parse(fs.readFileSync(path.join(ROOT, 'FINDINGS.json'), 'utf8'));
// The third axis. A field the ledger does not print is a field that drifts unseen,
// which is why `basis` renders here and why `at_risk` does from the moment it exists.
const R = require('./at-risk.js');

const NL = String.fromCharCode(10);
const out = [];
const w = s => out.push(s);

const compact = v => {
  if (v === null || v === undefined) return '';
  if (typeof v !== 'object') return String(v);
  return Object.entries(v)
    .map(([k, x]) => `${k}: ${typeof x === 'object' ? JSON.stringify(x) : x}`)
    .join('; ');
};

const preds = M.prediction_sets.flatMap(s => s.predictions);
const held = preds.filter(p => p.outcome === 'HELD').length;
const failed = preds.filter(p => p.outcome === 'FAILED').length;
const bites = M.traps_encountered.reduce((a, t) => a + t.count, 0);
const risk = R.tally(preds);
const LEAD = {
  'at-risk': '**At risk.**',
  'not-at-risk': '**Not at risk.**',
  'uncalled': '**At-risk verdict uncalled.**',
};

w('<!-- kind: results-ledger -->');
w('<!-- GENERATED by tools/render-ledger.js — do not edit by hand.');
w('     test/test-results.js fails if this file and the generator disagree. -->');
w('# 99 — The complete ledger');
w('');
w('Every registered prediction, in the order it was registered, rendered from');
w('[`FINDINGS.json`](../FINDINGS.json). **Nothing on this page is authored** — if a');
w('line here is wrong, the manifest is wrong.');
w('');
w(`**${M.prediction_sets.length} sets · ${preds.length} predictions · ${held} held · ${failed} failed**`);
w(`· ${M.unregistered_findings.length} measured but never registered`);
w(`· ${M.traps_encountered.length} defect classes, ${bites} occurrences`);
w('');
// Both rates, never one. A correction that hides what was previously claimed is a
// worse defect than the thing it corrects, so the raw counts above stand unaltered.
w(`Of those ${risk.total} predictions, **${risk.atRisk} were genuinely at risk**;`);
w(`${risk.notAtRisk} were not, and ${risk.uncalled} could not be called. The failure rate is`);
w(`therefore **${risk.rateCorrected}% of what was at risk** and ${risk.rateRaw}% of everything`);
w('registered. Both are true and they answer different questions —');
w('see `F-REGISTRATION-IS-NOT-RISK`.');
w('');
w('Each set names the commit that registered it and the commit that recorded its');
w('results. Those are checked to be genuinely ordered, and to be reachable from the');
w('branch rather than merely present in a local object store.');
w('');
w('---');
w('');

for (const s of M.prediction_sets) {
  const h = s.predictions.filter(p => p.outcome === 'HELD').length;
  const f = s.predictions.length - h;
  w(`## Set \`${s.id}\` — ${s.subject}`);
  w('');
  w(`| | |`);
  w(`|---|---|`);
  w(`| outcome | ${h} held, ${f} failed |`);
  w(`| tool | \`${s.tool}\` |`);
  w(`| asserted in | \`${s.asserted_in}\` |`);
  w(`| registered | \`${s.registered_at}\` |`);
  w(`| results | \`${s.results_at}\` |`);
  w('');
  for (const p of s.predictions) {
    // Two axes, not one. `outcome` is the prediction against the run; `basis` is the
    // scope of the claim -- measured at the width it was swept at, or argued at every
    // width. A field the ledger does not print is a field that drifts unseen, which is
    // why this renders as soon as the manifest carries it.
    const flag = R.label(p.at_risk);
    w(`### \`${p.id}\` — ${p.outcome}${p.basis === 'proven' ? ' · PROVEN' : ''}`
      + `${flag ? ` · ${flag}` : ''}`);
    w('');
    w(`**Claim.** ${p.claim}`);
    w('');
    if (R.reason(p.at_risk)) {
      w(`${LEAD[R.classify(p.at_risk)]} ${R.reason(p.at_risk)}`); w('');
    }
    if (p.argument) { w(`**Argument.** ${p.argument}`); w(''); }
    if (p.measured) { w(`**Measured.** ${compact(p.measured)}`); w(''); }
    if (p.note) { w(`**Note.** ${p.note}`); w(''); }
  }
  w('---');
  w('');
}

w('## Measured but never registered');
w('');
w('Facts established in passing. Listed separately so the pre-registration record is');
w('not inflated by things that were never at risk.');
w('');
for (const f of M.unregistered_findings) {
  w(`- **\`${f.id}\`**${f.basis === 'proven' ? ' · PROVEN' : ''} — ${f.claim}`);
  if (f.argument) w(`  <br>*Argument:* ${f.argument}`);
  // A finding that has since been narrowed must say so wherever it is read. This
  // field existed and was rendered nowhere, which is the same defect one level up.
  if (f.scope) w(`  <br>*Scope:* ${f.scope}`);
  if (f.evidence) w(`  <br>*Evidence:* ${f.evidence}`);
  if (f.asserted_in) w(`  <br>*Asserted in:* \`${f.asserted_in}\``);
}
// Empty today, and rendered only when it is not, so the first departure from the
// decoration audit's baseline appears here rather than only in a diff.
if ((M.reaudits || []).length) {
  w('');
  w('---');
  w('');
  w('## Re-audits');
  w('');
  w('Where a prediction\'s `at_risk` verdict departs from the baseline scored at');
  w('`1acfeee`, with the argument for departing and the commit that carries it. The');
  w('lists in `test/test-findings.js` are sticky, not immovable; this is the door.');
  w('');
  for (const r of M.reaudits) {
    w(`- **\`${r.id}\`** — ${r.from} → ${r.to}, at \`${r.at}\``);
    w(`  <br>*Registered wording:* ${r.registered_wording}`);
    w(`  <br>*Argument:* ${r.argument}`);
  }
}
w('');
w('---');
w('');
w('## Defect classes');
w('');
w('Each produced a wrong result that looked right. The count is how many times each');
w('recurred, which is itself a measure of how well naming a thing prevents it.');
w('');
w('| class | times | shape |');
w('|---|---|---|');
for (const t of M.traps_encountered) {
  const d = t.description.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
  w(`| \`${t.id}\` | ${t.count} | ${d} |`);
}
w('');

const text = out.join(NL) + NL;
// Only emit when run directly. `test/test-results.js` imports this to compare
// against the committed file, and a module that prints on import would pour a
// thousand lines into the middle of a test run.
if (require.main === module) {
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(ROOT, 'results', '99-ledger.md'), text);
    console.log(`wrote results/99-ledger.md — ${text.split(NL).length} lines`);
  } else {
    process.stdout.write(text);
  }
}
module.exports = { render: () => text };
